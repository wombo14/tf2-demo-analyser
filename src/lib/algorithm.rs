use crate::lib::general_settings::GeneralSettings;

#[cfg(feature = "parallel")]
use rayon::prelude::*;

#[cfg(feature = "parallel")]
static WORKER_POOL: std::sync::OnceLock<rayon::ThreadPool> = std::sync::OnceLock::new();

#[cfg(feature = "parallel")]
pub fn get_worker_pool() -> &'static rayon::ThreadPool {
    WORKER_POOL.get_or_init(|| {
        rayon::ThreadPoolBuilder::new()
            .thread_name(|i| format!("analyser-worker-{}", i))
            .build()
            .expect("Failed to initialize rayon thread pool for demo analysis")
    })
}

pub fn analyse_with_settings<'a>(
    demo: &Demo,
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
    settings: &GeneralSettings,
) -> anyhow::Result<CheatAnalyser<'a>> {
    let mut analyser = analyse_sequential(demo, algorithms)?;
    analyser.apply_sliding_window(settings);
    analyser.algorithms.clear();
    Ok(analyser)
}

pub fn analyse<'a>(
    demo: &Demo,
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
) -> anyhow::Result<CheatAnalyser<'a>> {
    let settings = GeneralSettings::load_default();
    analyse_with_settings(demo, algorithms, &settings)
}

pub fn analyse_bytes_with_settings<'a>(
    bytes: &[u8],
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
    settings: &GeneralSettings,
) -> anyhow::Result<CheatAnalyser<'a>> {
    let mut analyser = analyse_bytes_from_tick(bytes, algorithms, 0)?;
    analyser.apply_sliding_window(settings);
    Ok(analyser)
}

/// Analyses a demo without applying the sliding window filter. The algorithms only run from
/// `from_tick` on (0 = whole demo); the game state is still built from the start of the demo.
pub fn analyse_bytes_from_tick<'a>(
    bytes: &[u8],
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
    from_tick: u32,
) -> anyhow::Result<CheatAnalyser<'a>> {
    #[cfg(feature = "parallel")]
    {
        if algorithms.len() <= 1 {
            let demo = Demo::new(bytes);
            let mut analyser = analyse_sequential_from_tick(&demo, algorithms, from_tick)?;
            analyser.algorithms.clear();
            return Ok(analyser);
        }

        let names: Vec<&str> = algorithms.iter().map(|a| a.algorithm_name()).collect();
        let costs = algorithm_costs::estimate_costs(&names);
        let num_threads = algorithm_costs::worker_count(&costs);
        if num_threads <= 1 {
            let demo = Demo::new(bytes);
            let mut analyser = analyse_sequential_from_tick(&demo, algorithms, from_tick)?;
            analyser.algorithms.clear();
            return Ok(analyser);
        }

        let mut worker_algos: Vec<Vec<Box<dyn CheatAlgorithm<'a> + Send>>> =
            (0..num_threads).map(|_| Vec::new()).collect();
        let assignment = algorithm_costs::assign_workers(&costs, num_threads);
        for (algo, worker) in algorithms.into_iter().zip(assignment) {
            worker_algos[worker].push(algo);
        }
        worker_algos.retain(|chunk| !chunk.is_empty());

        let actual_workers = worker_algos.len();
        crate::reset_progress(actual_workers);

        let results: Vec<anyhow::Result<CheatAnalyser<'a>>> = get_worker_pool().install(|| {
            worker_algos
                .into_par_iter()
                .enumerate()
                .map(|(worker_id, chunk)| {
                    let thread_demo = Demo::new(bytes);
                    analyse_sequential_with_worker_id_from_tick(&thread_demo, Some(bytes), chunk, worker_id, from_tick)
                })
                .collect()
        });

        algorithm_costs::save();

        let mut merged = CheatAnalyser::new(vec![]);
        for res in results {
            let mut analyser = res?;
            if merged.parse_error.is_none() {
                merged.parse_error = analyser.parse_error.take();
            }
            if merged.header.is_none() {
                merged.header = analyser.header;
                merged.tick = analyser.tick;
                merged.state = analyser.state;
            } else {
                analyser.state.user_cmds.clear();
                analyser.state.user_cmds.shrink_to_fit();
                analyser.state.console_cmds.clear();
                analyser.state.console_cmds.shrink_to_fit();
            }
            analyser.algorithms.clear();
            merged.detections.extend(analyser.detections);
        }
        merged.detections.sort_by(|a, b| {
            a.tick
                .cmp(&b.tick)
                .then_with(|| a.player.cmp(&b.player))
                .then_with(|| a.algorithm.cmp(&b.algorithm))
        });
        merged.algorithms.clear();
        merged.state.user_cmds.clear();
        merged.state.user_cmds.shrink_to_fit();
        merged.state.console_cmds.clear();
        merged.state.console_cmds.shrink_to_fit();

        Ok(merged)
    }
    #[cfg(not(feature = "parallel"))]
    {
        let demo = Demo::new(bytes);
        let mut analyser = analyse_sequential_from_tick(&demo, algorithms, from_tick)?;
        analyser.algorithms.clear();
        Ok(analyser)
    }
}

pub fn analyse_bytes<'a>(
    bytes: &[u8],
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
) -> anyhow::Result<CheatAnalyser<'a>> {
    let settings = GeneralSettings::load_default();
    analyse_bytes_with_settings(bytes, algorithms, &settings)
}

pub fn analyse_sequential<'a>(
    demo: &Demo,
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
) -> anyhow::Result<CheatAnalyser<'a>> {
    analyse_sequential_from_tick(demo, algorithms, 0)
}

pub fn analyse_sequential_from_tick<'a>(
    demo: &Demo,
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
    from_tick: u32,
) -> anyhow::Result<CheatAnalyser<'a>> {
    crate::reset_progress(1);
    let mut analyser = analyse_sequential_with_worker_id_from_tick(demo, None, algorithms, 0, from_tick)?;
    algorithm_costs::save();
    analyser.state.user_cmds.clear();
    analyser.state.user_cmds.shrink_to_fit();
    analyser.state.console_cmds.clear();
    analyser.state.console_cmds.shrink_to_fit();
    Ok(analyser)
}

pub fn analyse_sequential_with_worker_id<'a>(
    demo: &Demo,
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
    worker_id: usize,
) -> anyhow::Result<CheatAnalyser<'a>> {
    analyse_sequential_with_worker_id_opt(demo, None, algorithms, worker_id)
}

pub fn analyse_sequential_with_worker_id_opt<'a>(
    demo: &Demo,
    demo_bytes: Option<&[u8]>,
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
    worker_id: usize,
) -> anyhow::Result<CheatAnalyser<'a>> {
    analyse_sequential_with_worker_id_from_tick(demo, demo_bytes, algorithms, worker_id, 0)
}

pub fn analyse_sequential_with_worker_id_from_tick<'a>(
    demo: &Demo,
    demo_bytes: Option<&[u8]>,
    algorithms: Vec<Box<dyn CheatAlgorithm<'a> + Send>>,
    worker_id: usize,
    from_tick: u32,
) -> anyhow::Result<CheatAnalyser<'a>> {
    let mut stream = demo.get_stream();
    let header: Header = Header::read(&mut stream)?;
    let mut packets = RawPacketStream::new(stream);

    let mut analyser = CheatAnalyser::new(algorithms);
    analyser.worker_id = worker_id;
    analyser.set_analyse_from_tick(from_tick);
    let mut handler = CheatDemoHandler::with_analyser(analyser);

    handler.handle_header(&header);
    let _ = handler.analyser.init();
    if let Some(bytes) = demo_bytes {
        handler.analyser.handle_demo_bytes(bytes);
    } else {
        let mut raw = demo.get_stream();
        let len = raw.bits_left() / 8;
        if let Ok(bytes) = raw.read_bytes(len) {
            handler.analyser.handle_demo_bytes(&bytes);
        }
    }
    loop {
        if crate::CANCEL_ANALYSIS.load(std::sync::atomic::Ordering::Relaxed) {
            anyhow::bail!("Analysis cancelled");
        }
        let packet = packets.next(&handler.state_handler);
        let packet = match packet {
            Ok(packet) => match packet {
                Some(packet) => packet,
                None => break,
            },
            Err(e) => {
                dev_print!("ParseError: {}", e);
                // The packet stream ends at the first error; what was read so far is still analysed.
                handler.analyser.parse_error.get_or_insert_with(|| e.to_string());
                continue;
            }
        };
        let _ = handler.handle_packet(packet)?;
        handler.analyser.update_message_filter();
    }
    if packets.incomplete {
        handler
            .analyser
            .parse_error
            .get_or_insert_with(|| "demo ends unexpectedly (truncated or still recording)".to_string());
    }
    let _ = handler.analyser.finish()?;
    // Costs are learned per analysed tick, a partial analysis would skew them.
    if algorithm_costs::COST_LEARNING && from_tick == 0 {
        algorithm_costs::record(&handler.analyser.measured_algorithm_costs(), handler.analyser.tick.into());
    }
    Ok(handler.analyser)
}

pub trait CheatAlgorithm<'a> {
    fn default(&self) -> bool {
        panic!("default() not set for {}", std::any::type_name::<Self>());
    }

    fn algorithm_name(&self) -> &str {
        panic!("algorithm_name() not implemented for {}", std::any::type_name::<Self>());
    }

    /// Short tooltip or description explaining the algorithm's purpose in the UI / CLI.
    fn tooltip(&self) -> &'static str {
        algorithm_tooltip(self.algorithm_name()).unwrap_or("")
    }

    fn params(&mut self) -> Option<&mut Parameters>{
        None
    }

    // Return true if the algorithm can't start in the middle of a demo, e.g. because it tracks
    // entities from their creation. The live scanner, which otherwise only analyses the part
    // recorded since its previous scan, then always runs it on the whole demo.
    fn needs_whole_demo(&self) -> bool {
        false
    }

    // Ticks of history the algorithm needs before its detections are the same as when it ran on
    // the whole demo (a rolling window, the 60 ticks JankGuard ignores after a spawn...). The
    // live scanner starts the algorithm this long before the part it wants the detections of, so
    // return no more than needed: every tick costs processing time. Not used when
    // needs_whole_demo() is true.
    fn live_warmup_ticks(&self) -> u32 {
        crate::lib::live_scan::DEFAULT_LIVE_WARMUP_TICKS
    }

    fn does_handle(&self, message_type: MessageType) -> bool {
        match self.handled_messages() {
            Ok(types) => types.contains(&message_type),
            Err(parse_all) => parse_all,
        }
    }

    // Called before any other events
    // Use this instead of ::new() when performing any non-ephemeral actions e.g. modifying files
    fn init(&mut self) -> Result<(), Error> {
        Ok(())
    }

    // Called for each tick. Passes the basic game state for the tick
    // Try the write_to_file algorithm to see what those states look like (there is one state per line)
    // cargo run -- -i demo.dem -a write_to_file
    fn on_tick(&mut self, _state: &CheatAnalyserState, _parser_state: &ParserState) -> Result<Vec<Detection>, Error> {
        Ok(vec![])
    }

    // If your algorithm needs to handle additional message types, return those types in a Vec.
    // You can return Err(true) to accept all messages, or Err(false) to reject all messages.
    fn handled_messages(&self) -> Result<Vec<MessageType>, bool> {
        Err(false)
    }

    // Called for each message received by the parser.
    // Only called for types specified in handled_messages.
    fn on_message(&mut self, _message: &Message, _state: &CheatAnalyserState, _parser_state: &ParserState, _tick: DemoTick) -> Result<Vec<Detection>, Error> {
        Ok(vec![])
    }

    // Called once before parsing with the raw demo file
    // Use for checks on the file container itself (header bookkeeping, frame layout)
    fn on_demo_bytes(&mut self, _bytes: &[u8]) -> Result<Vec<Detection>, Error> {
        Ok(vec![])
    }

    // Called for every signon and message packet, after its messages were handled
    fn on_packet(&mut self, _packet: &PacketInfo) -> Result<Vec<Detection>, Error> {
        Ok(vec![])
    }

    // Called for every string table entry (signon tables, dem_stringtables block and table updates)
    fn on_string_entry(&mut self, _table: &str, _index: usize, _entry: &StringTableEntry, _state: &CheatAnalyserState) -> Result<Vec<Detection>, Error> {
        Ok(vec![])
    }

    // Called after all other events
    // Use for cleaning up or for aggregate analysis
    fn finish(&mut self) -> Result<Vec<Detection>, Error> {
        Ok(vec![])
    }
}

/// Framing information of a signon or message packet.
pub struct PacketInfo {
    pub tick: DemoTick,
    pub signon: bool,
    /// Bits left in the payload after the last message (0..=6) and their value.
    pub tail_bits: u8,
    pub tail_value: u8,
}

#[derive(Serialize, Deserialize, Clone)]
pub struct Detection {
    pub tick: u32,
    pub algorithm: String,
    pub player: u64,
    pub data: Value
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_all_default_stable_algorithms_have_tooltips() {
        let proven = get_proven_algorithms();
        for algo in &proven {
            if algo.default() {
                let name = algo.algorithm_name();
                let tip = algo.tooltip();
                assert!(!tip.is_empty(), "Stable algorithm '{}' is enabled by default but has no tooltip", name);
                assert!(algorithm_tooltip(name).is_some(), "algorithm_tooltip('{}') returned None", name);
            }
        }
    }
}
